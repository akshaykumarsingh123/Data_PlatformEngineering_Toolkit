-- Generating Dynamic SQL in Snowflake
SELECT 'GRANT ' || ROLE || ' ON USER SVC_MKT_CDP_DEV TO ROLE ' || GRANTEE_NAME || ';' 
 FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS
WHERE GRANTEE_NAME = 'SVC_MKT_CDP_DEV';


-- Generating GRANT Ownership command through Dynamic SQL
SELECT 'GRANT OWNERSHIP ON TABLE '||
    table_catalog AS database_name,
    '.'|| table_schema AS schema_name,
    '.'||table_name || ' TO ROLE FR_MKT_CDP COPY CURRENT GRANTS;'
   FROM MKT_CDP.INFORMATION_SCHEMA.TABLES
WHERE table_owner = 'FR_MKT_EXTERNAL_CDP';

-- Find Schema owned by FR_MKT_EXTERNAL_CDP

SELECT * FROM SNOWFLAKE.ACCOUNT_USAGE.SCHEMATA
WHERE CATALOG_NAME='MKT_CDP' AND SCHEMA_OWNER='FR_MKT_EXTERNAL_CDP';