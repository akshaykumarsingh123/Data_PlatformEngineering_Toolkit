--Daily Account Storage Trend

SELECT 
    USAGE_DATE,
    (AVG(STORAGE_BYTES) + AVG(STAGE_BYTES) + AVG(FAILSAFE_BYTES) + AVG(HYBRID_TABLE_STORAGE_BYTES)) / (1024 * 1024 * 1024) AS total_storage_gb
FROM SNOWFLAKE.ACCOUNT_USAGE.STORAGE_USAGE
WHERE USAGE_DATE >= DATEADD(DAY, -30, CURRENT_DATE())
GROUP BY USAGE_DATE
ORDER BY USAGE_DATE DESC;

--Monthly Account Storage Trend (Last 365 Days)

SELECT 
    USAGE_DATE,
    (AVG(STORAGE_BYTES) + AVG(STAGE_BYTES) + AVG(FAILSAFE_BYTES) + AVG(HYBRID_TABLE_STORAGE_BYTES)) / (1024 * 1024 * 1024) AS total_storage_gb
FROM SNOWFLAKE.ACCOUNT_USAGE.STORAGE_USAGE
--WHERE USAGE_DATE >= DATEADD(MONTH, -6, CURRENT_DATE())
--WHERE USAGE_DATE>= '2025-01-01'
GROUP BY USAGE_DATE
ORDER BY USAGE_DATE DESC;

--Weekly Account Storage Trend
SELECT 
    USAGE_DATE,
    AVG(STORAGE_BYTES) / (1024 * 1024 * 1024) AS storage_gb,
    AVG(STAGE_BYTES) / (1024 * 1024 * 1024) AS stage_gb,
    AVG(FAILSAFE_BYTES) / (1024 * 1024 * 1024) AS failsafe_gb,
    AVG(HYBRID_TABLE_STORAGE_BYTES) / (1024 * 1024 * 1024) AS hybrid_gb
FROM SNOWFLAKE.ACCOUNT_USAGE.STORAGE_USAGE
WHERE USAGE_DATE >= DATEADD(DAY, -30, CURRENT_DATE())
GROUP BY USAGE_DATE
ORDER BY USAGE_DATE DESC;