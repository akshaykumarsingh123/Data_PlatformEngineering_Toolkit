CREATE OR REPLACE PROCEDURE DBA_ADMIN.DBO.SP_GET_USER_PERMISSIONS("USER_NAME" VARCHAR)
RETURNS TABLE ("GRANTEE_NAME" VARCHAR, "ROLE" VARCHAR, "GRANTED_BY" VARCHAR)
LANGUAGE SQL
COMMENT='user-defined procedure'
EXECUTE AS OWNER
AS '
DECLARE 
    RES RESULTSET DEFAULT
    (
    SELECT GRANTEE_NAME,ROLE,GRANTED_BY 
    FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_USERS 
    WHERE GRANTEE_NAME=:USER_NAME
    );
BEGIN
    RETURN TABLE(RES);
END;
';