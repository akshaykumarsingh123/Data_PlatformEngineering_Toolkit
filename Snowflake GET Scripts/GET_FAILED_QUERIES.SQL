CREATE OR REPLACE PROCEDURE DBA_ADMIN.DBO.SP_GET_FAILED_QUERIES("LOOK_BACK_DAYS" NUMBER(38,0))
RETURNS TABLE ("QUERY_ID" VARCHAR, "USER_NAME" VARCHAR, "QUERY_TEXT" VARCHAR, "ERROR_MESSAGE" VARCHAR, "START_TIME" TIMESTAMP_LTZ(9))
LANGUAGE SQL
COMMENT='user-defined procedure'
EXECUTE AS OWNER
AS '
DECLARE
    res RESULTSET;
BEGIN
    res := (
        SELECT 
            CAST(QUERY_ID AS VARCHAR) AS QUERY_ID,
            CAST(USER_NAME AS VARCHAR) AS USER_NAME,
            CAST(QUERY_TEXT AS VARCHAR) AS QUERY_TEXT,
            CAST(ERROR_MESSAGE AS VARCHAR) AS ERROR_MESSAGE,
            CAST(START_TIME AS TIMESTAMP_LTZ) AS START_TIME
        FROM SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY
        WHERE ERROR_CODE IS NOT NULL
        AND START_TIME >= DATEADD(DAY, -1*:LOOK_BACK_DAYS, CURRENT_TIMESTAMP())
        ORDER BY START_TIME DESC
    );
    RETURN TABLE(res);
END;
';