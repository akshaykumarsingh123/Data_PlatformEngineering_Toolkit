CREATE OR REPLACE PROCEDURE DBA_ADMIN.DBO.SP_GET_DATABASE_PERMISSIONS("DATABASE_NAME" VARCHAR)
RETURNS TABLE ("GRANTEE_NAME" VARCHAR, "DATABASE_NAME" VARCHAR, "GRANTED_ON" VARCHAR, "PRIVILEGE" VARCHAR)
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE 
    RES RESULTSET DEFAULT
    (
    SELECT GRANTEE_NAME, TABLE_CATALOG AS DATABASE_NAME, GRANTED_ON, PRIVILEGE 
    FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES 
    WHERE TABLE_CATALOG=:DATABASE_NAME AND  GRANTEE_NAME!= ''SYSADMIN''
    ORDER BY GRANTEE_NAME
    );
BEGIN
    RETURN TABLE(RES);
END;
';