CREATE OR REPLACE PROCEDURE DBA_ADMIN.DBO.SP_GET_ROLE_HIERARCHY_PER_DATAMART("DATAMART" VARCHAR)
RETURNS TABLE ("ROLE_NAME" VARCHAR, "HIERARCHY_LEVEL" NUMBER(38,0), "ROLE_HIERARCHY_PATH" VARCHAR)
LANGUAGE SQL
EXECUTE AS OWNER
AS '
DECLARE
    RES RESULTSET DEFAULT
    (
    WITH RECURSIVE ROLE_HIERARCHY AS (
        -- BASE CASE: START WITH DIRECT ROLE-TO-ROLE GRANTS
        SELECT 
            GRANTEE_NAME AS ROLE_NAME,
            GRANTED_TO AS PARENT_ROLE,
            NAME AS CHILD_ROLE,
            1 AS HIERARCHY_LEVEL,
            ARRAY_CONSTRUCT(NAME) AS ROLE_PATH
        FROM SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES
        WHERE GRANTED_TO = ''ROLE''
            AND GRANTED_ON = ''ROLE''
            AND GRANTEE_NAME NOT IN (
                ''SECURITYADMIN'',''SYSADMIN'',''ACCOUNTADMIN'',
                ''ADM_INFRAARCHITECT'',''ADM_DBA_ADMIN'',''MS_DBA''
            )
            AND DELETED_ON IS NULL

        UNION ALL

        -- RECURSIVE CASE
        SELECT
            RH.ROLE_NAME,
            RH.PARENT_ROLE,
            GTR.NAME AS CHILD_ROLE,
            RH.HIERARCHY_LEVEL + 1 AS HIERARCHY_LEVEL,
            ARRAY_APPEND(RH.ROLE_PATH, GTR.NAME) AS ROLE_PATH
        FROM ROLE_HIERARCHY RH
        JOIN SNOWFLAKE.ACCOUNT_USAGE.GRANTS_TO_ROLES GTR
            ON RH.CHILD_ROLE = GTR.GRANTEE_NAME
        WHERE GTR.GRANTED_TO = ''ROLE''
            AND GTR.GRANTEE_NAME NOT IN (
                ''SECURITYADMIN'',''SYSADMIN'',''ACCOUNTADMIN'',
                ''ADM_INFRAARCHITECT'',''ADM_DBA_ADMIN'',''MS_DBA''
            )
            AND GTR.GRANTED_ON = ''ROLE''
            AND GTR.DELETED_ON IS NULL
            AND GTR.PRIVILEGE = ''USAGE''
    )
    SELECT 
        ROLE_NAME,
        HIERARCHY_LEVEL,
        ARRAY_TO_STRING(ROLE_PATH, '' --> '') AS ROLE_HIERARCHY_PATH
    FROM ROLE_HIERARCHY
    WHERE HIERARCHY_LEVEL = 3
        AND ROLE_NAME ILIKE ''%'' || :DATAMART || ''%''
    ORDER BY ROLE_NAME, HIERARCHY_LEVEL, ROLE_HIERARCHY_PATH
);
BEGIN
    RETURN TABLE(RES);
END;
';